#!/usr/bin/env python3
"""Converts images/*.TGA into src/pad_images.hpp, so the sample needs no CD.

Sent over the USB DevCart (ftx -x), the program has no disc to load files from.
Colors follow SaturnRingLib's TGA loader (srl_tga.hpp), so the result looks the same.
Run after changing an image: python3 make_images.py  (needs Pillow)
"""
import struct
from pathlib import Path
from PIL import Image

HERE = Path(__file__).parent


def rgb555(r, g, b):
    # 1BBBBBGGGGGRRRRR, top bit = opaque (SRL HighColor::FromRGB555)
    return 0x8000 | (b >> 3) << 10 | (g >> 3) << 5 | (r >> 3)


def argb(r, g, b, a):
    # SRL TGA::ParseArgb: transparent only when mostly transparent AND black
    return 0 if a < 128 and (r, g, b) == (0, 0, 0) else rgb555(r, g, b)


def array(ctype, name, values):
    fmt = "0x%04x" if ctype == "uint16_t" else "0x%02x"
    rows = [", ".join(fmt % v for v in values[i:i + 16]) for i in range(0, len(values), 16)]
    return "alignas(4) static const %s %s[] = {\n    %s,\n};\n" % (ctype, name, ",\n    ".join(rows))


def main():
    out = ["// Generated by make_images.py from images/*.TGA: do not edit.", "#pragma once", "#include <stdint.h>", ""]

    pad = Image.open(HERE / "images/GAMEPAD.TGA")
    assert pad.mode == "P", pad.mode
    # palette size from the TGA header (bytes 5-6): Pillow pads the palette to 256
    count = struct.unpack_from("<H", (HERE / "images/GAMEPAD.TGA").read_bytes(), 5)[0]
    pal = pad.getpalette()[:count * 3]
    out.append("constexpr uint16_t GamepadWidth = %d, GamepadHeight = %d, GamepadColors = %d;" % (*pad.size, count))
    out.append(array("uint16_t", "GamepadPalette", [rgb555(*pal[i:i + 3]) for i in range(0, len(pal), 3)]))
    pixels = list(pad.tobytes())
    assert max(pixels) < count
    out.append(array("uint8_t", "GamepadPixels", pixels))

    for name in ("WIRE", "ARROW", "BUTTON"):
        img = Image.open(HERE / f"images/{name}.TGA").convert("RGBA")
        cap = name.capitalize()
        out.append("constexpr uint16_t %sWidth = %d, %sHeight = %d;" % (cap, img.size[0], cap, img.size[1]))
        rgba = img.tobytes()
        out.append(array("uint16_t", cap + "Pixels", [argb(*rgba[i:i + 4]) for i in range(0, len(rgba), 4)]))

    (HERE / "src/pad_images.hpp").write_text("\n".join(out))


if __name__ == "__main__":
    main()
